"""
DecrypTrace — Watermark Extractor (Backend / Investigator side)

Extracts embedded DCT watermarks from leaked PDF documents.
This runs on the BACKEND for the investigator workflow.

The extraction is "blind" — it does not require the original
unwatermarked image to recover the watermark.
"""
import os
import hashlib
import hmac
import logging
import tempfile
from pathlib import Path
from dataclasses import dataclass

import numpy as np
import fitz  # PyMuPDF

logger = logging.getLogger("decryptrace.watermark.extractor")

# Watermark secret must match the recipient-agent's secret
WATERMARK_SECRET = b"decryptrace-watermark-secret-change-in-production"


@dataclass
class ExtractionResult:
    """Result of watermark extraction from a document."""
    watermark_detected: bool
    watermark_id: str | None
    integrity_valid: bool | None
    confidence: float
    page_extracted_from: int
    error: str | None = None

    def to_dict(self) -> dict:
        return {
            "watermark_detected": self.watermark_detected,
            "watermark_id": self.watermark_id,
            "integrity_valid": self.integrity_valid,
            "confidence": self.confidence,
            "page_extracted_from": self.page_extracted_from,
            "error": self.error,
        }


def extract_watermark_from_pdf(pdf_path: str) -> ExtractionResult:
    """
    Extract embedded watermark from a PDF document.

    Pipeline:
    1. Open PDF with PyMuPDF
    2. Render each page as an image
    3. Attempt blind watermark extraction using blind_watermark
    4. Validate watermark integrity tag
    5. Return watermark ID if found

    Args:
        pdf_path: Path to the leaked PDF file.

    Returns:
        ExtractionResult with watermark detection status.
    """
    try:
        doc = fitz.open(pdf_path)
    except Exception as e:
        return ExtractionResult(
            watermark_detected=False,
            watermark_id=None,
            integrity_valid=None,
            confidence=0.0,
            page_extracted_from=-1,
            error=f"Could not open PDF: {e}",
        )

    try:
        from blind_watermark import WaterMark

        for page_num in range(min(doc.page_count, 5)):  # Check first 5 pages
            page = doc[page_num]
            # Render page as image
            pix = page.get_pixmap(dpi=150)
            img_data = pix.tobytes("png")

            # Save to temp file for blind_watermark
            with tempfile.NamedTemporaryFile(suffix=".png", delete=False) as tmp:
                tmp.write(img_data)
                tmp_path = tmp.name

            try:
                # Attempt extraction
                bwm = WaterMark(password_img=1, password_wm=1)
                # Extract watermark - expecting 128 bits
                wm_extract = bwm.extract(tmp_path, wm_shape=128, mode="bit")

                if wm_extract is not None and len(wm_extract) > 0:
                    # Convert bits to hex string
                    wm_bits = np.array(wm_extract[:128], dtype=np.uint8)
                    wm_bytes = np.packbits(wm_bits)
                    wm_hex = wm_bytes.tobytes().hex().upper()
                    watermark_id = f"WM-{wm_hex[:8]}"

                    logger.info(
                        f"Watermark extracted from page {page_num}: {watermark_id}"
                    )

                    return ExtractionResult(
                        watermark_detected=True,
                        watermark_id=watermark_id,
                        integrity_valid=True,  # Simplified for prototype
                        confidence=0.95,
                        page_extracted_from=page_num,
                    )
            except Exception as e:
                logger.debug(f"Extraction failed on page {page_num}: {e}")
            finally:
                os.unlink(tmp_path)

    except ImportError:
        logger.warning("blind_watermark not available, using fallback extraction")
    except Exception as e:
        logger.error(f"Watermark extraction error: {e}")
    finally:
        doc.close()

    return ExtractionResult(
        watermark_detected=False,
        watermark_id=None,
        integrity_valid=None,
        confidence=0.0,
        page_extracted_from=-1,
        error="No watermark detected in document",
    )


def validate_watermark_integrity(
    watermark_id: str,
    document_hash: str,
    recipient_key_fingerprint: str,
    session_id: str,
    expected_tag: str,
) -> bool:
    """
    Validate the integrity tag embedded in the watermark.

    The tag proves the watermark was generated by the trusted system,
    not forged by an attacker.

    Args:
        watermark_id: Extracted watermark ID (e.g., "WM-7A92")
        document_hash: SHA3-256 hash of the original document
        recipient_key_fingerprint: Recipient's key fingerprint
        session_id: Decryption session ID
        expected_tag: The integrity tag to validate against

    Returns:
        True if the integrity tag is valid.
    """
    integrity_input = (
        watermark_id + document_hash + recipient_key_fingerprint + session_id
    ).encode("utf-8")

    computed_tag = hmac.new(
        WATERMARK_SECRET, integrity_input, hashlib.sha3_256
    ).hexdigest()[:16]

    return hmac.compare_digest(computed_tag, expected_tag)
